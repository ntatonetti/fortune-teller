"""Measure Madame Mechanika's face mesh on static/img/mechanika/base.png and write
static/js/mechanika-mesh.js, which the guest's face is warped onto during the flicker.
Rerun it whenever base.png changes.

Usage: .venv/bin/python scripts/measure_face.py   (server must be running on :8000;
needs scipy in .venv for the triangulation: .venv/bin/pip install scipy)
"""

import json
import os
from pathlib import Path

from playwright.sync_api import sync_playwright
from scipy.spatial import Delaunay

ROOT = Path(__file__).resolve().parent.parent
os.environ.setdefault("PLAYWRIGHT_BROWSERS_PATH", str(ROOT / ".venv" / "ms-playwright"))

# MediaPipe face-mesh points that tie the two faces together. The outline comes
# first, in order round the face, so its edge can be feathered.
IDX = [
    # face outline, forehead round to chin and back
    10, 338, 297, 332, 284, 251, 389, 356, 454, 323, 361, 288, 397, 365, 379, 378, 400, 377,
    152, 148, 176, 149, 150, 136, 172, 58, 132, 93, 234, 127, 162, 21, 54, 103, 67, 109,
    # brows
    70, 63, 105, 66, 107, 336, 296, 334, 293, 300,
    # eyes: corners, lids, irises
    33, 160, 158, 133, 153, 144, 362, 385, 387, 263, 373, 380, 468, 473,
    # nose: bridge, tip, wings, base
    168, 6, 197, 195, 5, 4, 1, 2, 98, 327, 129, 358,
    # mouth: corners, lips
    61, 291, 0, 17, 13, 14, 37, 267, 84, 314,
    # cheeks and chin
    50, 280, 205, 425, 199,
]
OUTLINE = 36

# Her face fills too little of the full scene for the detector, so the mesh runs
# on a close-up like a guest at the booth: this part of the photo, at 1280 x 960.
MEASURE = """async () => {
  const { Watcher } = await import("/js/watcher.js");
  const w = new Watcher(document.createElement("video"));
  await w.start();
  while (!w.landmarker) await new Promise((r) => setTimeout(r, 200));
  const img = new Image();
  img.src = "/img/mechanika/base.png";
  await img.decode();
  const R = { x: 528, y: 98, w: 360, h: 270 };
  const cam = document.createElement("canvas");
  cam.width = 1280;
  cam.height = 960;
  cam.getContext("2d").drawImage(img, R.x, R.y, R.w, R.h, 0, 0, 1280, 960);
  const lm = w.landmarker.detect(cam).faceLandmarks[0];
  return lm.map((q) => [R.x + q.x * R.w, R.y + q.y * R.h]);
}"""

with sync_playwright() as p:
    browser = p.chromium.launch(args=["--use-fake-ui-for-media-stream", "--use-fake-device-for-media-stream"])
    page = browser.new_page()
    page.goto("http://localhost:8000/")
    mesh = page.evaluate(MEASURE)
    browser.close()

her = [[round(mesh[i][0], 1), round(mesh[i][1], 1)] for i in IDX]
tris = Delaunay(her).simplices.tolist()
out = ROOT / "static" / "js" / "mechanika-mesh.js"
out.write_text(
    "// Generated by scripts/measure_face.py from static/img/mechanika/base.png; rerun it if that changes.\n"
    "// Face-mesh points (MediaPipe indices) where they sit on her photo, and the\n"
    "// triangles between them that the guest's face is warped through.\n"
    f"export const IDX = {json.dumps(IDX)};\n"
    f"export const OUTLINE = {OUTLINE}; // the first points go round her face\n"
    f"export const HER = {json.dumps(her)};\n"
    f"export const TRIS = {json.dumps(tris)};\n"
)
print(f"{len(her)} points, {len(tris)} triangles -> {out.relative_to(ROOT)}")
